-- BarberCEN - Esquema inicial para Supabase (PostgreSQL)
-- Ejecutar completo desde Supabase Dashboard > SQL Editor.

create table if not exists public.clientes (
    id_cliente bigint generated by default as identity primary key,
    nombre varchar(50) not null,
    apellido varchar(50) not null,
    telefono varchar(25),
    email varchar(100),
    created_at timestamptz not null default now()
);

-- RLS protege la tabla. Estas políticas abiertas son SOLO para pruebas
-- escolares sin inicio de sesión: cualquier visitante puede leer, crear,
-- modificar y eliminar clientes. No usar con datos reales ni en producción.
alter table public.clientes enable row level security;

drop policy if exists "Acceso de prueba para clientes" on public.clientes;
create policy "Acceso de prueba para clientes"
on public.clientes
for all
to anon
using (true)
with check (true);

grant select, insert, update, delete on public.clientes to anon;
grant usage, select on sequence public.clientes_id_cliente_seq to anon;
